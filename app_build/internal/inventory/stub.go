// LoadVehiclesFromJSONFile carga un catálogo vehicular desde un archivo JSON local sin requerir recompilación.
func LoadVehiclesFromJSONFile(path string) ([]Vehicle, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var vehicles []Vehicle
	if err := json.Unmarshal(raw, &vehicles); err != nil {
		return nil, err
	}
	return vehicles, nil
}

